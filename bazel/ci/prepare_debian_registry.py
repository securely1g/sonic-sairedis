"""Select the reviewed Draft package inputs without changing the local main RC."""
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
MAIN = "https://raw.githubusercontent.com/securely1g/sonic-bazel-registry/main"
BRANCH = "codex/source-debian-runtime-permissions"
REVISION = "7f8a0fd08ceb36cfaca9645a24e7f1dd174e0302"
REGISTRY = MAIN.removesuffix("main") + BRANCH

if __name__ == "__main__":
    observed = subprocess.check_output(["git", "ls-remote", "https://github.com/securely1g/sonic-bazel-registry.git", "refs/heads/" + BRANCH], text=True).split()
    if observed != [REVISION, "refs/heads/" + BRANCH]:
        raise SystemExit("The reviewed registry branch changed; refresh and revalidate its pin.")
    original = (ROOT / ".bazelrc").read_text()
    if original.count("common --registry=" + MAIN) != 1:
        raise SystemExit("Expected the maintained main registry in .bazelrc")
    destination = ROOT / "artifacts/validation/debian-registry"
    destination.mkdir(parents=True, exist_ok=True)
    effective = destination / "effective.bazelrc"
    effective.write_text("# AUTO-GENERATED by prepare_debian_registry.py. DO NOT EDIT MANUALLY.\n" + original.replace(MAIN, REGISTRY))
    (destination / "inputs.json").write_text(json.dumps({"_generated": "AUTO-GENERATED by prepare_debian_registry.py. DO NOT EDIT MANUALLY.", "registry": REGISTRY, "revision": REVISION}, indent=2) + "\n")
    binary = shutil.which("bazel")
    if not binary or not os.environ.get("GITHUB_PATH"):
        raise SystemExit("Run this preparation step after installing Bazel in GitHub Actions")
    directory = destination / "bin"
    directory.mkdir(exist_ok=True)
    wrapper = directory / "bazel"
    wrapper.write_text(
        "#!/bin/sh\n# AUTO-GENERATED by prepare_debian_registry.py. DO NOT EDIT MANUALLY.\n"
        + 'if [ "${1:-}" = --version ]; then exec ' + shlex.quote(binary) + ' "$@"; fi\n'
        + "exec " + shlex.quote(binary) + " --noworkspace_rc --bazelrc="
        + shlex.quote(str(effective)) + ' "$@"\n'
    )
    wrapper.chmod(0o755)
    with open(os.environ["GITHUB_PATH"], "a") as output:
        output.write(str(directory) + "\n")
